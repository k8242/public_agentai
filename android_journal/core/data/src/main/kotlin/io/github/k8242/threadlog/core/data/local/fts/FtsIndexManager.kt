package io.github.k8242.threadlog.core.data.local.fts

import androidx.room.useReaderConnection
import androidx.room.useWriterConnection
import io.github.k8242.threadlog.core.data.local.ThreadLogDatabase
import io.github.k8242.threadlog.core.data.local.dao.EntryDao
import io.github.k8242.threadlog.core.data.local.dao.TagDao
import io.github.k8242.threadlog.core.data.mapper.toDomain
import io.github.k8242.threadlog.core.model.TagState
import javax.inject.Inject
import javax.inject.Singleton

data class FtsRawMatch(
    val entryId: String,
    val snippetMarked: String,
)

/**
 * Manages synchronization and full-text search against the SQLite FTS5 `entries_fts`
 * virtual table using Room 2.8.5 `useWriterConnection` / `useReaderConnection` APIs
 * backed by `BundledSQLiteDriver`.
 */
@Singleton
class FtsIndexManager @Inject constructor(
    private val database: ThreadLogDatabase,
    private val entryDao: EntryDao,
    private val tagDao: TagDao,
) {

    /**
     * Reindexes a single entry in `entries_fts`. Soft-deleted or missing entries are removed
     * from the FTS5 index; active entries are upserted with `body_plain`, visible tags, and
     * hidden auto-tags (excluding `AUTO_REJECTED`).
     */
    suspend fun reindexEntry(entryId: String) {
        val entry = entryDao.getById(entryId)
        if (entry == null || entry.deletedAtMs != null) {
            removeEntry(entryId)
            return
        }

        val entryTags = tagDao.getEntryTagsForEntry(entryId)
        val tagIds = entryTags.map { it.tagId }.distinct()
        val tagsById = if (tagIds.isEmpty()) {
            emptyMap()
        } else {
            tagDao.getByIds(tagIds).associateBy { it.id }
        }

        val visibleTags = entryTags
            .filter { it.state == TagState.USER.name || it.state == TagState.AUTO_PROMOTED.name }
            .mapNotNull { tagsById[it.tagId]?.toDomain() }
        val hiddenTags = entryTags
            .filter { it.state == TagState.AUTO_HIDDEN.name }
            .mapNotNull { tagsById[it.tagId]?.toDomain() }

        val visibleText = FtsQueryBuilder.buildTagIndexText(visibleTags)
        val hiddenText = FtsQueryBuilder.buildTagIndexText(hiddenTags)

        database.useWriterConnection { connection ->
            connection.usePrepared(DELETE_BY_ENTRY_ID_SQL) { stmt ->
                stmt.bindText(1, entryId)
                stmt.step()
            }
            connection.usePrepared(INSERT_FTS_ROW_SQL) { stmt ->
                stmt.bindText(1, entryId)
                stmt.bindText(2, entry.bodyPlain)
                stmt.bindText(3, visibleText)
                stmt.bindText(4, hiddenText)
                stmt.step()
            }
        }
    }

    /** Reindexes multiple entries sequentially on the active connection or writer pool. */
    suspend fun reindexEntries(entryIds: Collection<String>) {
        for (entryId in entryIds.distinct()) {
            reindexEntry(entryId)
        }
    }

    /** Removes [entryId] from `entries_fts`. */
    suspend fun removeEntry(entryId: String) {
        database.useWriterConnection { connection ->
            connection.usePrepared(DELETE_BY_ENTRY_ID_SQL) { stmt ->
                stmt.bindText(1, entryId)
                stmt.step()
            }
        }
    }

    /** Clears and rebuilds the entire `entries_fts` index from all active entries. */
    suspend fun rebuildAll() {
        database.useWriterConnection { connection ->
            connection.usePrepared(DELETE_ALL_SQL) { stmt ->
                stmt.step()
            }
        }
        val activeIds = entryDao.getAllActiveIds()
        reindexEntries(activeIds)
    }

    /**
     * Executes a sanitized FTS5 `MATCH` query and returns matching entry IDs with `<mark>`
     * highlighted snippets generated by SQLite's `snippet(entries_fts, 1, ...)`.
     */
    suspend fun search(
        queryTokens: List<String>,
        includeHiddenAutoTags: Boolean,
    ): List<FtsRawMatch> {
        val matchExpr = FtsQueryBuilder.buildMatchExpression(
            tokens = queryTokens,
            includeHiddenAutoTags = includeHiddenAutoTags,
        ) ?: return emptyList()

        return database.useReaderConnection { connection ->
            connection.usePrepared(SEARCH_SQL) { stmt ->
                stmt.bindText(1, matchExpr)
                val matches = mutableListOf<FtsRawMatch>()
                while (stmt.step()) {
                    val entryId = stmt.getText(0)
                    val snippet = if (stmt.isNull(1)) "" else stmt.getText(1)
                    matches += FtsRawMatch(
                        entryId = entryId,
                        snippetMarked = snippet,
                    )
                }
                matches
            }
        }
    }

    private companion object {
        const val DELETE_BY_ENTRY_ID_SQL = "DELETE FROM entries_fts WHERE entry_id = ?"
        const val DELETE_ALL_SQL = "DELETE FROM entries_fts"
        const val INSERT_FTS_ROW_SQL =
            "INSERT INTO entries_fts(entry_id, body_plain, visible_tags, hidden_tags) VALUES (?, ?, ?, ?)"
        const val SEARCH_SQL =
            "SELECT entry_id, snippet(entries_fts, 1, '<mark>', '</mark>', '…', 20) " +
                "FROM entries_fts " +
                "WHERE entries_fts MATCH ?"
    }
}
